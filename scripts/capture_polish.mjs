// Repeatable before/after captures of the existing five-minute demo, at recording sizes.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const require=createRequire(path.join(root,'web/package.json'));
const { chromium,expect }=require('@playwright/test');
const phase=process.argv[2];
if(!['before','after'].includes(phase))throw new Error('Use before or after');
const output=path.join(root,'review/visual-polish',phase);
fs.mkdirSync(output,{recursive:true});
const browser=await chromium.launch({args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const records=[];const errors=[];
try{
  for(const [width,height] of [[1440,1000],[1920,1080]]){
    const page=await browser.newPage({viewport:{width,height},deviceScaleFactor:1});
    page.on('pageerror',e=>errors.push(e.message));
    const shot=async(name,locator)=>{
      const file=`${width}-${name}.png`;
      if(locator)await locator.screenshot({path:path.join(output,file),animations:'disabled'});
      else await page.screenshot({path:path.join(output,file),animations:'disabled'});
      const dimensions=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
      if(dimensions.scrollWidth>dimensions.width)throw new Error(`Overflow ${file}`);
      records.push({file,width,height,state:name});
    };
    await page.goto(process.env.DEMO_URL||'http://127.0.0.1:3000');
    await page.getByRole('button',{name:'Predict coronary risk',exact:true}).click();
    await expect(page.getByText(/held-out demonstration ·/)).toBeVisible({timeout:90000});
    await expect(page.getByText(/FPS · live/)).toBeVisible({timeout:20000});
    await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
    await shot('workspace');
    await shot('explanation',page.locator('.explanation-panel'));
    await page.getByRole('button',{name:'Select LCX in 3D'}).click();
    await page.getByRole('button',{name:'X-ray',exact:true}).click();
    await shot('lcx-xray');
    await page.getByRole('button',{name:'Select RCA in 3D'}).click();
    await page.getByRole('button',{name:'Vessels only',exact:true}).click();
    await shot('rca-isolated');
    await page.getByRole('button',{name:'Vessels only',exact:true}).click();
    await page.getByRole('button',{name:'X-ray',exact:true}).click();
    await page.getByRole('button',{name:'Evidence Lab',exact:true}).click();
    await page.getByRole('tab',{name:'CAD',exact:true}).click();
    await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
    await shot('validation');
    await shot('comparisons',page.locator('.lab-two-columns').first());
    await page.getByRole('tab',{name:'LCX',exact:true}).click();
    await shot('thresholds',page.locator('.research-thresholds'));
    await page.getByRole('tab',{name:'Interpretability',exact:true}).click();
    await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
    await shot('global-shap');
    await page.getByRole('tab',{name:'Robustness',exact:true}).click();
    await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
    await shot('robustness');
    await page.getByRole('tab',{name:'Data & provenance',exact:true}).click();
    await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
    await shot('provenance');
    await page.getByRole('button',{name:'Patient workspace',exact:true}).click();
    await page.getByLabel('Explore a held-out case').selectOption({label:'Held-out failure case'});
    await page.getByRole('button',{name:'Predict coronary risk',exact:true}).click();
    await expect(page.getByText(/held-out demonstration ·/)).toBeVisible({timeout:90000});
    await page.getByRole('tab',{name:'CAD',exact:true}).click();
    await page.getByRole('button',{name:'Reveal recorded outcomes'}).click();
    await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
    await shot('failure');
    await page.getByLabel('Explore a held-out case').selectOption({label:'Lower CAD estimate'});
    await page.getByRole('button',{name:'Predict coronary risk',exact:true}).click();
    await expect(page.getByText(/held-out demonstration ·/)).toBeVisible({timeout:90000});
    await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
    await shot('second-patient');
    await page.getByLabel('Age',{exact:true}).fill('85');
    await shot('stale');
    await page.close();
  }
  if(errors.length)throw new Error(JSON.stringify(errors));
  fs.writeFileSync(path.join(output,'index.json'),JSON.stringify({phase,records,browser_errors:errors},null,2));
  console.log(`${phase}: ${records.length} captures at both recording sizes; no page errors or horizontal overflow.`);
}finally{await browser.close();}
